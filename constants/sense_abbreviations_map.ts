  export function expandAbbreviation(value: string, type: 'pos' | 'tags' | 'field' = 'pos'): string {
    if (!value) return value;
    const map = sensesAbbreviationMap[type] as Record<string, string>;
    const parts = value.split(', ');
    return parts.map((p: string) => map[p.trim()] || p.trim()).join(', ');
  }
  
  export function expandSense(sense: { pos: string; tags: string; field: string }) {
    return {
      ...sense,
      pos: expandAbbreviation(sense.pos, 'pos'),
      tags: expandAbbreviation(sense.tags, 'tags'),
      field: expandAbbreviation(sense.field, 'field')
    };
  }
  
